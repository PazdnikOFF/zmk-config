/*
 * Вставка распознанного текста в поле с фокусом.
 *
 * Основной путь — буфер обмена и ⌘V (код клавиши 9: физическая V, при русской
 * раскладке тоже вставляет). Наш текст помечен org.nspasteboard.TransientType —
 * менеджеры буфера его не сохраняют, — а прежнее содержимое буфера
 * возвращается через 0,8 с после последней вставки, если за это время его никто
 * не поменял.
 *
 * Запасной путь — набор символами через CGEvent с unicode-строкой: для полей,
 * которые кусочную вставку через буфер не принимают.
 */

/// Буфер обмена: временная запись и возврат прежнего содержимого.
final class DictationClipboard {
    static let shared = DictationClipboard()

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let restoreDelay: TimeInterval = 0.8

    private let board = NSPasteboard.general
    private var saved: [[NSPasteboard.PasteboardType: Data]]?
    private var ourChange = -1
    private var restoreTimer: Timer?

    private func snapshot() -> [[NSPasteboard.PasteboardType: Data]] {
        (board.pasteboardItems ?? []).map { item in
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { copy[type] = data }
            }
            return copy
        }
    }

    /// Положить текст для одной вставки. Прежнее содержимое запоминается один раз на серию.
    func writeTransient(_ text: String) {
        restoreTimer?.invalidate()
        restoreTimer = nil
        if saved == nil || board.changeCount != ourChange {
            saved = snapshot()
        }
        board.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: DictationClipboard.transientType)
        item.setData(Data(), forType: DictationClipboard.autoGeneratedType)
        board.writeObjects([item])
        ourChange = board.changeCount
    }

    func scheduleRestore() {
        restoreTimer?.invalidate()
        restoreTimer = Timer.scheduledTimer(
            withTimeInterval: DictationClipboard.restoreDelay, repeats: false
        ) { [weak self] _ in self?.restore() }
    }

    private func restore() {
        restoreTimer = nil
        defer { saved = nil }
        // Человек успел что-то скопировать сам — его содержимое не трогаем.
        guard board.changeCount == ourChange, let saved else { return }
        board.clearContents()
        let items: [NSPasteboardItem] = saved.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { board.writeObjects(items) }
    }

    /// Оставить текст в буфере насовсем (фокус сменился, поле защищено).
    func keep(_ text: String) {
        restoreTimer?.invalidate()
        restoreTimer = nil
        saved = nil
        ourChange = -1
        board.clearContents()
        board.setString(text, forType: .string)
    }
}

/// Почему текст не вставлен, а оставлен в буфере.
enum DictationDivert {
    case focusChanged(String)
    case secureInput
    case noAccessibility
    case modifiersHeld

    var message: String {
        switch self {
        case .focusChanged: return "Фокус сменился — текст в буфере обмена"
        case .secureInput: return "Поле защищено — текст в буфере обмена"
        case .noAccessibility: return "Нет доступа к вводу — текст в буфере обмена"
        case .modifiersHeld: return "Зажаты ⌘⌥⌃⇧ — текст в буфере обмена"
        }
    }

    var logCode: String {
        switch self {
        case .focusChanged(let app): return "focus→\(app)"
        case .secureInput: return "secure_input"
        case .noAccessibility: return "no_ax"
        case .modifiersHeld: return "modifiers_held"
        }
    }
}

/*
 * Доставка текста одной диктовки: очередь кусков, строго по порядку, по одной
 * вставке за раз. Куски, пришедшие, пока идёт вставка, склеиваются в одну.
 */
final class DictationDelivery {
    struct Report {
        var pastedChars = 0
        var pastes = 0
        var firstPaste: TimeInterval?
        var lastPaste: TimeInterval?
        var diverted = ""
        var divert: DictationDivert?
    }

    /// Пауза между записью в буфер и ⌘V (как paste_delay_ms у Handy).
    static let beforeKeystroke: TimeInterval = 0.06
    /// Пауза после ⌘V, прежде чем снова менять буфер: приложение читает его асинхронно.
    static let afterKeystroke: TimeInterval = 0.06
    /// Сколько ждать отпускания модификаторов после конца диктовки.
    static let modifierGrace: TimeInterval = 2.0

    private static var askedAccessibility = false

    private let targetPID: pid_t
    private let method: DictationPasteMethod
    private let clock: () -> TimeInterval

    private var pending = ""
    private var busy = false
    private var finished = false
    private var finishedAt: TimeInterval = 0
    private var cancelled = false
    private var onDone: ((Report) -> Void)?
    private(set) var report = Report()

    /// Клавишу диктовки ещё держат (режим удержания) — модификаторы ждём без предела.
    var hotkeyHeld: () -> Bool = { false }

    init(targetPID: pid_t, method: DictationPasteMethod, clock: @escaping () -> TimeInterval) {
        self.targetPID = targetPID
        self.method = method
        self.clock = clock
    }

    func enqueue(_ text: String) {
        guard !text.isEmpty, !cancelled else { return }
        pending += text
        pump()
    }

    /// Кусков больше не будет; onDone — когда всё вставлено или отложено в буфер.
    func finish(onDone: @escaping (Report) -> Void) {
        finished = true
        finishedAt = clock()
        self.onDone = onDone
        pump()
    }

    func cancel() {
        cancelled = true
        pending = ""
        onDone = nil
    }

    private static func modifiersHeld() -> Bool {
        let flags = CGEventSource.flagsState(.combinedSessionState)
        return !flags.intersection([.maskCommand, .maskAlternate, .maskControl, .maskShift]).isEmpty
    }

    private func frontmostName() -> String {
        NSWorkspace.shared.frontmostApplication?.localizedName ?? "?"
    }

    private func pump() {
        guard !cancelled, !busy else { return }

        if pending.isEmpty {
            completeIfDone()
            return
        }

        if report.divert != nil {
            report.diverted += pending
            pending = ""
            completeIfDone()
            return
        }

        if IsSecureEventInputEnabled() {
            divert(.secureInput)
            return
        }
        if NSWorkspace.shared.frontmostApplication?.processIdentifier != targetPID {
            divert(.focusChanged(frontmostName()))
            return
        }
        if !AXIsProcessTrusted() {
            // Системный запрос — один раз за запуск, а не на каждую диктовку.
            if !DictationDelivery.askedAccessibility {
                DictationDelivery.askedAccessibility = true
                let prompt = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
                _ = AXIsProcessTrustedWithOptions([prompt: true] as CFDictionary)
            }
            divert(.noAccessibility)
            return
        }

        // Аккорд ещё зажат: ⌘V смешается с ним (⌥⌘V — другая команда). Ждём.
        if DictationDelivery.modifiersHeld() {
            if finished, !hotkeyHeld(), clock() - finishedAt >= DictationDelivery.modifierGrace {
                divert(.modifiersHeld)
                return
            }
            busy = true
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.03) { [weak self] in
                self?.busy = false
                self?.pump()
            }
            return
        }

        let text = pending
        pending = ""
        busy = true

        switch method {
        case .clipboard:
            DictationClipboard.shared.writeTransient(text)
            DispatchQueue.main.asyncAfter(deadline: .now() + DictationDelivery.beforeKeystroke) {
                [weak self] in
                guard let self else { return }
                guard !self.cancelled else {
                    // Отменили до ⌘V: вернуть людям их буфер.
                    DictationClipboard.shared.scheduleRestore()
                    self.busy = false
                    return
                }
                DictationKeys.commandV()
                self.noteSent(text)
                DictationClipboard.shared.scheduleRestore()
                DispatchQueue.main.asyncAfter(deadline: .now() + DictationDelivery.afterKeystroke) {
                    self.busy = false
                    self.pump()
                }
            }
        case .typing:
            DictationKeys.type(text)
            noteSent(text)
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.01) { [weak self] in
                self?.busy = false
                self?.pump()
            }
        }
    }

    private func noteSent(_ text: String) {
        let now = clock()
        if report.firstPaste == nil { report.firstPaste = now }
        report.lastPaste = now
        report.pastes += 1
        report.pastedChars += text.count
    }

    private func divert(_ reason: DictationDivert) {
        report.divert = reason
        report.diverted += pending
        pending = ""
        completeIfDone()
    }

    private func completeIfDone() {
        guard finished, pending.isEmpty, !busy, let onDone else { return }
        self.onDone = nil
        if report.divert != nil, !report.diverted.isEmpty {
            DictationClipboard.shared.keep(report.diverted)
        }
        onDone(report)
    }
}

/// Синтетические нажатия. Нужен доступ Accessibility (в macOS 27 — «Device Control and Data Access»).
enum DictationKeys {
    private static let vKey: CGKeyCode = 9  // kVK_ANSI_V
    private static let commandKey: CGKeyCode = 55  // kVK_Command

    private static func source() -> CGEventSource? {
        let source = CGEventSource(stateID: .combinedSessionState)
        // Пока идут наши события, физические клавиши не подмешиваются к ним.
        source?.setLocalEventsFilterDuringSuppressionState(
            [.permitLocalMouseEvents, .permitSystemDefinedEvents],
            state: .eventSuppressionStateSuppressionInterval)
        return source
    }

    static func commandV() {
        let source = source()
        let events = [
            CGEvent(keyboardEventSource: source, virtualKey: commandKey, keyDown: true),
            CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
            CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false),
            CGEvent(keyboardEventSource: source, virtualKey: commandKey, keyDown: false),
        ]
        for (index, event) in events.enumerated() {
            event?.flags = index == 3 ? [] : .maskCommand
            event?.post(tap: .cgAnnotatedSessionEventTap)
        }
    }

    /// Набор строки кусками по 20 UTF-16 — больше CGEvent за раз не берёт.
    static func type(_ text: String) {
        let source = source()
        var chunk: [UniChar] = []

        func flush() {
            guard !chunk.isEmpty else { return }
            for down in [true, false] {
                guard let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down)
                else { continue }
                event.flags = []
                chunk.withUnsafeBufferPointer { buffer in
                    event.keyboardSetUnicodeString(stringLength: buffer.count, unicodeString: buffer.baseAddress)
                }
                event.post(tap: .cgAnnotatedSessionEventTap)
            }
            chunk.removeAll(keepingCapacity: true)
        }

        for character in text {
            let units = Array(String(character).utf16)
            if chunk.count + units.count > 20 { flush() }
            chunk.append(contentsOf: units)
        }
        flush()
    }
}
