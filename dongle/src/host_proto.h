/*
 * Разбор строк от агента на маке. Общий для двух каналов: USB CDC (пока есть
 * кабель) и GATT-характеристики (когда донгл работает от батареи).
 */

#pragma once

#include <stddef.h>

#define HOST_LINE_MAX 96

/*
 * Скормить одну строку вида
 *
 *     layout=RU cpu=23 mem=61 disk=142 batt=87 chg=1
 *
 * Порядок ключей произвольный, незнакомые игнорируются, отсутствующие
 * сохраняют прежнее значение. Строка портится на месте (strtok_r), поэтому
 * передавать надо изменяемый буфер.
 *
 * Обновляет накопленное состояние и перерисовывает экран.
 */
void dongle_host_proto_feed(char *line);
